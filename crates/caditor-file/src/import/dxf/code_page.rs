#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_windows_code_page_decodes_its_own_letters() {
        let letters = [
            ("ANSI_874", 0xa1, 'ก'),
            ("ANSI_1250", 0x8a, 'Š'),
            ("ansi_1251", 0xc0, 'А'),
            ("ANSI_1252", 0x80, '€'),
            ("ANSI_1253", 0xc1, 'Α'),
            ("ANSI_1254", 0xd0, 'Ğ'),
            ("ANSI_1255", 0xe0, 'א'),
            ("ANSI_1256", 0xc7, 'ا'),
            ("ANSI_1257", 0xc0, 'Ą'),
            ("ANSI_1258", 0xd2, '\u{309}'),
            ("ISO8859-1", 0xe9, 'é'),
        ];

        for (name, byte, letter) in letters {
            let page = CodePage::named(name).unwrap();
            assert_eq!(page.decode(&[b'a', byte]), format!("a{letter}"), "{name}");
        }
        assert_eq!(CodePage::named("DOS437"), None);
        assert_eq!(CodePage::named("ANSI_932"), None);
    }

    #[test]
    fn utf8_text_stays_utf8_whatever_the_code_page() {
        let page = CodePage::named("ANSI_1251").unwrap();

        assert_eq!(page.decode("Größe".as_bytes()), "Größe");
        assert!(matches!(page.decode(b"plain"), Cow::Borrowed("plain")));
        assert_eq!(page.decode(&[0xc1, 0xee, 0xeb, 0xf2]), "Болт");
        assert_eq!(CodePage::DEFAULT.decode(&[0x81]), "\u{fffd}");
    }

    #[test]
    fn unicode_escapes_become_their_characters() {
        let page = CodePage::DEFAULT;

        assert_eq!(page.decode(br"\U+0411\U+043E\U+043B\U+0442"), "Болт");
        assert_eq!(page.decode(br"A\U+00e9B"), "AéB");
        assert_eq!(page.decode(br"\U+12G4 \U+D800 \U+"), r"\U+12G4 \U+D800 \U+");
    }
}
