use std::borrow::Cow;

const UPPER_HALF: u8 = 0x80;
const REPLACEMENT: char = '\u{fffd}';
const ESCAPE: &str = "\\U+";
const ESCAPE_DIGITS: usize = 4;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum CodePage {
    Windows(&'static [char; 128]),
    Latin1,
}

impl CodePage {
    pub const DEFAULT: Self = Self::Windows(&WINDOWS_1252);

    pub fn named(name: &str) -> Option<Self> {
        let name = name.trim().to_ascii_uppercase();
        if matches!(name.as_str(), "ISO8859-1" | "ISO_8859-1" | "ISO88591") {
            return Some(Self::Latin1);
        }
        let number: u16 = name.strip_prefix("ANSI_")?.parse().ok()?;
        Some(Self::Windows(match number {
            874 => &WINDOWS_874,
            1250 => &WINDOWS_1250,
            1251 => &WINDOWS_1251,
            1252 => &WINDOWS_1252,
            1253 => &WINDOWS_1253,
            1254 => &WINDOWS_1254,
            1255 => &WINDOWS_1255,
            1256 => &WINDOWS_1256,
            1257 => &WINDOWS_1257,
            1258 => &WINDOWS_1258,
            _ => return None,
        }))
    }

    pub fn decode(self, bytes: &[u8]) -> Cow<'_, str> {
        let text = match std::str::from_utf8(bytes) {
            Ok(text) => Cow::Borrowed(text),
            Err(_) => Cow::Owned(bytes.iter().map(|byte| self.character(*byte)).collect()),
        };
        unescaped(text)
    }

    fn character(self, byte: u8) -> char {
        match self {
            Self::Windows(table) if !byte.is_ascii() => table
                .get(usize::from(byte - UPPER_HALF))
                .copied()
                .unwrap_or(REPLACEMENT),
            Self::Windows(_) | Self::Latin1 => char::from(byte),
        }
    }
}

fn unescaped(text: Cow<'_, str>) -> Cow<'_, str> {
    if !text.contains(ESCAPE) {
        return text;
    }
    let mut out = String::with_capacity(text.len());
    let mut rest: &str = &text;
    while let Some(index) = rest.find(ESCAPE) {
        let (before, escape) = rest.split_at(index);
        out.push_str(before);
        let digits_end = ESCAPE.len() + ESCAPE_DIGITS;
        let character = escape
            .get(ESCAPE.len()..digits_end)
            .filter(|digits| digits.bytes().all(|byte| byte.is_ascii_hexdigit()))
            .and_then(|digits| u32::from_str_radix(digits, 16).ok())
            .and_then(char::from_u32);
        let consumed = match character {
            Some(character) => {
                out.push(character);
                digits_end
            }
            None => {
                out.push_str(ESCAPE);
                ESCAPE.len()
            }
        };
        rest = escape.get(consumed..).unwrap_or_default();
    }
    out.push_str(rest);
    Cow::Owned(out)
}

